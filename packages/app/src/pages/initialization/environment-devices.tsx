import type { PreviewManifest } from "@blame/agent-runtime"
import { Input } from "@/components/ui/input"
import { Textarea } from "@/components/ui/textarea"
import {
  EnvironmentSection,
  KindIcon,
  containerAnchor,
} from "./environment-kinds"

export type DeviceTarget = NonNullable<PreviewManifest["devices"]>[number]
export function EnvironmentDevices({ devices }: { devices: DeviceTarget[] }) {
  if (!devices.length) return null
  return (
    <EnvironmentSection
      title="Devices"
      description="Apps built and run on your computer's simulators and emulators."
    >
      <div className="grid gap-3">
        {devices.map((target) => (
          <article
            key={target.id}
            tabIndex={-1}
            id={containerAnchor("device", target.id)}
            className="rounded-xl border p-4"
          >
            <div className="mb-3 flex items-center gap-2">
              <KindIcon kind={target.platform} className="size-4" />
              <h4 className="text-sm font-semibold">{target.id}</h4>
            </div>
            <dl className="grid gap-2 text-sm sm:grid-cols-2">
              <div>
                <dt className="text-muted-foreground">Platform</dt>
                <dd>
                  {target.platform === "ios"
                    ? "iOS Simulator"
                    : "Android Emulator"}
                </dd>
              </div>
              <div>
                <dt className="text-muted-foreground">Toolchain</dt>
                <dd>{target.toolchain}</dd>
              </div>
              <div>
                <dt className="text-muted-foreground">Scheme or module</dt>
                <dd>
                  {target.build.scheme ??
                    target.build.module ??
                    "Generated by the project"}
                </dd>
              </div>
              <div>
                <dt className="text-muted-foreground">App identifier</dt>
                <dd className="break-all">
                  {target.app.bundleId ?? target.app.applicationId}
                </dd>
              </div>
              <div>
                <dt className="text-muted-foreground">Device</dt>
                <dd>
                  {target.device?.model ?? "Default phone"}
                  {target.device?.os ? ` · ${target.device.os}` : ""}
                </dd>
              </div>
            </dl>
            {target.dependsOn?.length ? (
              <p className="mt-3 text-sm text-muted-foreground">
                Waits for {target.dependsOn.join(", ")}.
              </p>
            ) : null}
          </article>
        ))}
      </div>
    </EnvironmentSection>
  )
}
export function DeviceTargetFields({
  target,
  onChange,
}: {
  target: DeviceTarget
  onChange(target: DeviceTarget): void
}) {
  const buildFields = [
    ["workspace", "Xcode workspace"],
    ["project", "Xcode project"],
    ["scheme", "Scheme"],
    ["configuration", "Configuration"],
    ["module", "Gradle module"],
    ["variant", "Build variant"],
    ["flavor", "Flutter flavor"],
    ["target", "Flutter entry point"],
  ] as const
  const appFields = [
    ["bundleId", "Bundle identifier"],
    ["applicationId", "Application identifier"],
    ["launchActivity", "Launch activity"],
  ] as const
  return (
    <fieldset className="grid gap-4 rounded-xl border p-4">
      <legend className="px-1 text-sm font-semibold">{target.id}</legend>
      <label className="grid gap-1 text-sm">
        Prepare commands
        <Textarea
          value={target.prepare?.join("\n") ?? ""}
          onChange={(e) =>
            onChange({
              ...target,
              prepare: e.target.value.split("\n").filter((line) => line.trim()),
            })
          }
          placeholder="One command per line"
        />
      </label>
      <div className="grid gap-3 sm:grid-cols-2">
        {buildFields.map(([key, label]) => (
          <label key={key} className="grid gap-1 text-sm">
            {label}
            <Input
              value={target.build[key] ?? ""}
              onChange={(e) => {
                const build = { ...target.build }
                if (e.target.value) build[key] = e.target.value
                else delete build[key]
                onChange({ ...target, build })
              }}
            />
          </label>
        ))}
        {appFields.map(([key, label]) => (
          <label key={key} className="grid gap-1 text-sm">
            {label}
            <Input
              value={target.app[key] ?? ""}
              onChange={(e) => {
                const app = { ...target.app }
                if (e.target.value) app[key] = e.target.value
                else delete app[key]
                onChange({ ...target, app })
              }}
            />
          </label>
        ))}
        {(["model", "os"] as const).map((key) => (
          <label key={key} className="grid gap-1 text-sm">
            {key === "model" ? "Device model" : "OS version"}
            <Input
              value={target.device?.[key] ?? ""}
              onChange={(e) => {
                const device = { ...target.device }
                if (e.target.value) device[key] = e.target.value
                else delete device[key]
                onChange({ ...target, device })
              }}
            />
          </label>
        ))}
      </div>
    </fieldset>
  )
}
